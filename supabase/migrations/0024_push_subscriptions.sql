-- =============================================================================
-- X AutoHub — Notificaciones push (después del pivote)
-- =============================================================================
--
-- Avisar al cliente cuando su pedido sale o su cita se confirma, sin que el equipo
-- tenga que escribirle a mano. El aviso llega al teléfono o a la computadora donde la
-- persona lo activó (la PWA ya es instalable).
--
-- Esta migración solo guarda **dónde** avisar: una fila por dispositivo. Quién avisa y
-- qué dice lo decide la Edge Function `send-push` (supabase/functions/send-push), que
-- se llama desde el panel después de cambiar el estado de un pedido o de una cita.
--
--   · `push_subscriptions`: la suscripción que el navegador entrega (un `endpoint` y dos
--     claves). Cada quien ve y borra solo las suyas.
--   · `register_push_subscription()`: la única forma de guardar una. Es una función y no
--     un insert por dos razones: (1) un mismo dispositivo puede cambiar de dueño (alguien
--     cierra sesión y entra otra persona), y el `endpoint` es único, así que la fila
--     vieja de la otra cuenta hay que reemplazarla, y una política de RLS no deja tocar
--     filas ajenas; (2) pone un tope de dispositivos por cuenta.
--
--
-- LO QUE SE DECIDIÓ
-- ------------------
-- · **Solo cuentas.** Un pedido de invitado no tiene dueño, así que no hay a quién
--   avisar. Es lo mismo que ya pasa con "Mis pedidos".
-- · **El navegador nunca manda lo que se dice.** La función lee el pedido o la cita de la
--   base y arma el texto ella; el panel solo le dice cuál cambió.
-- · **Un dispositivo, una fila.** Cuando el servicio de push responde que la suscripción
--   ya no existe (404 o 410), la función la borra.
--
--
-- ORDEN DE DESPLIEGUE
-- -------------------
-- Migración → función (`send-push`, con sus secretos) → frontend. El frontend anterior no
-- sabe nada de esto y sigue funcionando.
--
-- ESTA MIGRACIÓN SE PUEDE EJECUTAR DOS VECES: todo lleva `if not exists` /
-- `create or replace` / `drop ... if exists`.
-- =============================================================================

create table if not exists public.push_subscriptions (
  id         bigint generated by default as identity primary key,
  user_id    uuid    not null references public.profiles(id) on delete cascade,
  -- La URL del servicio de push (Google, Mozilla, Apple…). Única: es el dispositivo.
  endpoint   text    not null unique check (endpoint like 'https://%' and char_length(endpoint) <= 2048),
  -- Las dos claves que el navegador entrega, en base64url. Sirven para cifrar el aviso.
  p256dh     text    not null check (char_length(p256dh) between 80 and 100),
  auth       text    not null check (char_length(auth) between 20 and 30),
  user_agent text    not null default '' check (char_length(user_agent) <= 300),
  created_at timestamptz not null default now()
);

create index if not exists push_subscriptions_user_idx on public.push_subscriptions (user_id);

comment on table public.push_subscriptions is
  'Dispositivos donde un usuario quiere recibir avisos. Se escribe solo con register_push_subscription(); la lee la Edge Function send-push.';

alter table public.push_subscriptions enable row level security;

-- Cada quien ve y borra los suyos (desactivar los avisos es borrar la fila).
drop policy if exists "cada quien ve sus dispositivos" on public.push_subscriptions;
create policy "cada quien ve sus dispositivos"
  on public.push_subscriptions for select
  using (auth.uid() = user_id);

drop policy if exists "cada quien borra sus dispositivos" on public.push_subscriptions;
create policy "cada quien borra sus dispositivos"
  on public.push_subscriptions for delete
  using (auth.uid() = user_id);

-- Sin política de insert ni de update: se escribe solo por la función. Y como los
-- default privileges de Supabase le dan permiso de escritura a las tablas nuevas, se
-- quita aquí también (defensa en profundidad).
revoke all on public.push_subscriptions from anon;
revoke insert, update on public.push_subscriptions from authenticated;


-- -----------------------------------------------------------------------------
-- register_push_subscription(): guardar este dispositivo
-- -----------------------------------------------------------------------------

create or replace function public.register_push_subscription(
  p_endpoint   text,
  p_p256dh     text,
  p_auth       text,
  p_user_agent text default ''
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  c_max_devices constant integer := 10;
  v_user uuid := auth.uid();
begin
  if v_user is null then
    raise exception 'Inicia sesion para activar los avisos.' using errcode = '42501';
  end if;

  -- Un mismo dispositivo no puede estar a nombre de dos cuentas: la que entra se lo
  -- queda. (Si fuera de otra persona, esa dejó de recibir avisos aquí: es lo correcto.)
  delete from public.push_subscriptions s where s.endpoint = p_endpoint;

  insert into public.push_subscriptions (user_id, endpoint, p256dh, auth, user_agent)
  values (v_user, p_endpoint, p_p256dh, p_auth, left(coalesce(p_user_agent, ''), 300));

  -- Un tope por cuenta: se conservan los más recientes.
  delete from public.push_subscriptions s
  where s.user_id = v_user
    and s.id not in (
      select id from public.push_subscriptions
      where user_id = v_user
      order by created_at desc, id desc
      limit c_max_devices
    );
end;
$$;

comment on function public.register_push_subscription(text, text, text, text) is
  'Guarda el dispositivo actual para recibir avisos. Cambia de dueño si el dispositivo estaba a nombre de otra cuenta.';

-- Las tres líneas de siempre (`revoke ... from public` no le quita nada a `anon`).
revoke all on function public.register_push_subscription(text, text, text, text) from public;
revoke execute on function public.register_push_subscription(text, text, text, text) from anon;
grant execute on function public.register_push_subscription(text, text, text, text) to authenticated;
