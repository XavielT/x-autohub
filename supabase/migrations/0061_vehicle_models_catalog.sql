--
-- La 0017 sembró modelos solo para las diez primeras marcas (88). Las otras 25
-- (Mazda, Mercedes-Benz, BMW, Lexus, Subaru, Isuzu, BYD...) quedaron con cero, así
-- que el selector de la tienda, el garaje y el formulario de compatibilidad
-- mostraban la marca y ningún modelo: caían al campo de texto libre.
--
-- Esta migración agrega los modelos de esas 25 marcas y completa los de las diez
-- primeras con los que más se ven en RD (429 nuevos; el total pasa de 88 a 517).
--
--   · Solo INSERTA: no toca modelos existentes ni sus ids, así que los garajes y
--     las compatibilidades que ya apuntan a un modelo siguen igual.
--   · El slug lo pone el trigger `vehicle_models_slug`.
--   · Los modelos que un usuario escribió a mano (`profile_vehicles.model_text`)
--     no se migran solos: el panel (Inventario → Marcas y modelos) los lista como
--     "sin modelo" y los pasa al modelo real con `admin_assign_vehicle_model()`.
--
-- ESTA MIGRACIÓN SE PUEDE EJECUTAR DOS VECES (`on conflict do nothing`).
-- La lista se espeja en `src/shared/data/vehicle.mock.ts`: si cambias una, cambia la otra.
-- =============================================================================

