-- =============================================================================
-- X AutoHub — Avisos push para quien agendó una cita sin cuenta
-- =============================================================================
--
-- La 0034 dejó que quien compró sin cuenta active los avisos de **su pedido**. Esta migración hace lo mismo con las
-- **citas del taller**: quien agenda sin cuenta puede pedir que le avisen cuando la cita se confirme, se esté trabajando en
-- su vehículo o quede lista.
--
--   · `appointment_push_subscriptions`: un dispositivo atado a **una cita**, no a una cuenta. Sin RLS abierta y sin
--     permisos para el navegador: la lee y la borra `send-push` con la clave de servicio.
--   · `register_appointment_push()` / `unregister_appointment_push()`: la única forma de guardar y quitar uno.
--   · `notify_status_change()` avisa de una cita sin dueño si tiene dispositivos (hasta aquí solo lo hacía con los pedidos).
--
--
-- LO QUE SE DECIDIÓ
-- ------------------
-- · **El uuid de la cita es la llave**, como el del pedido en la 0034: quien acaba de agendar recibió ese id en la
--   pantalla de confirmación y es lo único que hace falta. Un uuid no se adivina.
-- · **Solo citas de invitado y en marcha.** Con dueño, los avisos van a su cuenta (y registrar aquí los duplicaría); una cita
--   terminada (hecha, cancelada o a la que no se presentó) ya no cambia.
-- · **Hasta 3 dispositivos por cita.** El mismo dispositivo otra vez es una actualización.
-- · **Se limpia sola**: las filas se borran con la cita (`on delete cascade`) y `send-push` las borra al mandar el aviso de un
--   estado final.
-- · **Los rechazos usan el código 22023**, el único que la interfaz deja pasar con su mensaje en español.
-- · **Sin los secretos del Vault no se avisa, y tampoco falla**, como en la 0028.
--
--
-- ORDEN DE DESPLIEGUE
-- -------------------
-- Función `send-push` nueva (lee los dispositivos de la cita) → migración → frontend. Con la migración y la función vieja, el
-- trigger llamaría a `send-push` y esta respondería `guest`: no pasa nada. El frontend anterior no sabe de esto.
--
-- ESTA MIGRACIÓN SE PUEDE EJECUTAR DOS VECES: `if not exists`, `create or replace` y `drop ... if exists`.
-- =============================================================================

create table if not exists public.appointment_push_subscriptions (
  id             bigint generated by default as identity primary key,
  appointment_id uuid    not null references public.service_appointments(id) on delete cascade,
  endpoint       text    not null check (endpoint like 'https://%' and char_length(endpoint) <= 2048),
  p256dh         text    not null check (char_length(p256dh) between 80 and 100),
  auth           text    not null check (char_length(auth) between 20 and 30),
  user_agent     text    not null default '' check (char_length(user_agent) <= 300),
  created_at     timestamptz not null default now(),
  unique (appointment_id, endpoint)
);

create index if not exists appointment_push_subscriptions_appt_idx
  on public.appointment_push_subscriptions (appointment_id);

comment on table public.appointment_push_subscriptions is
  'Dispositivos de quien agendó una cita sin cuenta, atados a esa cita (0035). Se escribe con register_appointment_push(); la lee y la borra send-push.';

-- Nadie del navegador la toca: sin políticas y sin permisos. `send-push` entra con `service_role`.
alter table public.appointment_push_subscriptions enable row level security;
revoke all on public.appointment_push_subscriptions from public;
revoke all on public.appointment_push_subscriptions from anon;
revoke all on public.appointment_push_subscriptions from authenticated;
grant select, insert, update, delete on public.appointment_push_subscriptions to service_role;


-- -----------------------------------------------------------------------------
-- register_appointment_push(): activar los avisos de una cita de invitado
-- -----------------------------------------------------------------------------
create or replace function public.register_appointment_push(
  p_appointment_id uuid,
  p_endpoint       text,
  p_p256dh         text,
  p_auth           text,
  p_user_agent     text default ''
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  c_max_devices constant integer := 3;
  v_owner  uuid;
  v_status text;
begin
  select a.user_id, a.status into v_owner, v_status
    from public.service_appointments a where a.id = p_appointment_id;

  if not found then
    raise exception 'Esa cita no existe.' using errcode = '22023';
  end if;

  if v_owner is not null then
    raise exception 'Esta cita es de una cuenta: inicia sesion y activa los avisos desde tu perfil.' using errcode = '22023';
  end if;

  if v_status in ('done', 'cancelled', 'no_show') then
    raise exception 'Esta cita ya termino: no va a cambiar de estado.' using errcode = '22023';
  end if;

  -- El mismo dispositivo otra vez es una actualizacion, no un dispositivo mas.
  if not exists (
       select 1 from public.appointment_push_subscriptions s
        where s.appointment_id = p_appointment_id and s.endpoint = p_endpoint
     )
     and (select count(*) from public.appointment_push_subscriptions s where s.appointment_id = p_appointment_id) >= c_max_devices then
    raise exception 'Esta cita ya avisa a % dispositivos.', c_max_devices using errcode = '22023';
  end if;

  insert into public.appointment_push_subscriptions (appointment_id, endpoint, p256dh, auth, user_agent)
  values (p_appointment_id, p_endpoint, p_p256dh, p_auth, left(coalesce(p_user_agent, ''), 300))
  on conflict (appointment_id, endpoint) do update
    set p256dh = excluded.p256dh, auth = excluded.auth, user_agent = excluded.user_agent;
end;
$$;

comment on function public.register_appointment_push(uuid, text, text, text, text) is
  'Quien agendo sin cuenta activa los avisos de su cita en este dispositivo (0035). El uuid de la cita es la llave.';

revoke all on function public.register_appointment_push(uuid, text, text, text, text) from public;
grant execute on function public.register_appointment_push(uuid, text, text, text, text) to anon, authenticated;


-- -----------------------------------------------------------------------------
-- unregister_appointment_push(): quitar este dispositivo de una cita
-- -----------------------------------------------------------------------------
create or replace function public.unregister_appointment_push(p_appointment_id uuid, p_endpoint text)
returns void
language sql
security definer
set search_path = public
as $$
  delete from public.appointment_push_subscriptions where appointment_id = p_appointment_id and endpoint = p_endpoint;
$$;

revoke all on function public.unregister_appointment_push(uuid, text) from public;
grant execute on function public.unregister_appointment_push(uuid, text) to anon, authenticated;


-- -----------------------------------------------------------------------------
-- notify_status_change(): también las citas sin dueño que tienen dispositivos
-- -----------------------------------------------------------------------------
-- La de la 0034, con un cambio: una cita sin dueño avisa si tiene dispositivos suscritos, igual que un pedido. Sin
-- dispositivos no se hace ninguna llamada.
create or replace function public.notify_status_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_url    text;
  v_anon   text;
  v_secret text;
begin
  if new.user_id is null then
    -- Sin dueño: solo si hay dispositivos de invitado suscritos a este pedido o a esta cita.
    if not (
         case tg_table_name
           when 'orders' then exists (select 1 from public.order_push_subscriptions s where s.order_id = new.id)
           else exists (select 1 from public.appointment_push_subscriptions s where s.appointment_id = new.id)
         end
       ) then
      return null;
    end if;
  elsif new.user_id = auth.uid() then
    -- Quien cambia lo suyo ya lo sabe.
    return null;
  end if;

  begin
    select max(decrypted_secret) filter (where name = 'send_push_url'),
           max(decrypted_secret) filter (where name = 'send_push_anon_key'),
           max(decrypted_secret) filter (where name = 'send_push_secret')
      into v_url, v_anon, v_secret
      from vault.decrypted_secrets
     where name in ('send_push_url', 'send_push_anon_key', 'send_push_secret');

    if coalesce(v_url, '') = '' or coalesce(v_anon, '') = '' or coalesce(v_secret, '') = '' then
      return null;
    end if;

    perform net.http_post(
      url     := v_url,
      body    := jsonb_build_object(
                   'kind', case tg_table_name when 'orders' then 'order' else 'appointment' end,
                   'id',   new.id
                 ),
      headers := jsonb_build_object(
                   'Content-Type',  'application/json',
                   'Authorization', 'Bearer ' || v_anon,
                   'x-push-secret', v_secret
                 )
    );
  exception when others then
    raise warning 'notify_status_change: %', sqlerrm;
  end;

  return null;
end;
$$;

comment on function public.notify_status_change() is
  'Trigger: cuando cambia el estado de un pedido o de una cita con dueño (o sin dueño pero con dispositivos de invitado), le pide a la Edge Function send-push que avise (pg_net, con los secretos del Vault). Nunca hace fallar el cambio.';

-- Una función de trigger no se invoca por rpc, pero se cierra igual (las tres líneas).
revoke all on function public.notify_status_change() from public;
revoke execute on function public.notify_status_change() from anon;
revoke execute on function public.notify_status_change() from authenticated;
