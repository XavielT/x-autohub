-- =============================================================================
-- 0067 — Búsqueda que entiende cómo habla la gente: sinónimos, categoría, alias y errores de tecleo
-- =============================================================================
-- Lo que fallaba (visto en producción el 27/11/2026):
--
--   · "frenos" no encontraba los discos ni las pastillas: el nombre del producto no dice "frenos", su CATEGORÍA sí, y la
--     categoría no entraba en la búsqueda.
--   · Los alias (0042) solo los usaban las sugerencias de la barra; la página /buscar no los veía.
--   · Nadie podía buscar "bumper", "goma", "mofle", "balata" ni "croche": no había forma de enseñarle esas equivalencias.
--   · Las sugerencias de "fren" traían "Intercooler front mount": `word_similarity` sin umbral serio coincidía por dos trigramas.
--
-- Qué trae:
--
--   1. `search_synonym_groups`: grupos de términos intercambiables ({parachoques, bumper, defensa}). Públicos de lectura (no hay nada
--      sensible) y los escribe un admin desde Admin → Búsqueda. Viene sembrada con el habla de RD.
--   2. `xah_synonyms(palabra)` y `xah_query_words(consulta)`: expanden cada palabra de la consulta a ella misma con prefijo (lo que se
--      escribe: "bump" encuentra "bumper") OR sus sinónimos EXACTOS (sin prefijo, para que "ac" no encuentre "acero").
--   3. `search_products()` se reescribe con la misma firma y columnas (la 0023 es la base, con el número de parte de la 0051 incluido):
--      busca en nombre, marca, descripción, SKU, número de parte, NOMBRE DE LA CATEGORÍA (y la del padre) y ALIAS; entiende sinónimos;
--      perdona un error de tecleo en una palabra de 5 letras o más; y ordena mejor: lo que dice el nombre sube sobre lo que solo
--      dice la categoría.
--   4. `suggest_products()` igual: sinónimos y categoría, y los trigramas sueltos se acotan (la causa del "front mount").
--
-- ORDEN DE DESPLIEGUE: primero esta migración, después el frontend. El frontend anterior sigue funcionando (mismas firmas y columnas).
-- Se puede ejecutar dos veces.
-- =============================================================================

create extension if not exists pg_trgm with schema extensions;


-- -----------------------------------------------------------------------------
-- 1. Grupos de sinónimos
-- -----------------------------------------------------------------------------

create table if not exists public.search_synonym_groups (
  id         bigint generated by default as identity primary key,
  terms      text[] not null,
  created_at timestamptz not null default now()
);

comment on table public.search_synonym_groups is
  'Términos intercambiables en la búsqueda (parachoques = bumper = defensa). Todos van en minúsculas y sin tildes; un trigger los normaliza.';

-- Minúsculas, sin tildes, espacios colapsados, sin repetidos ni vacíos. Mínimo dos términos distintos.
create or replace function public.search_synonym_groups_normalize()
returns trigger
language plpgsql
set search_path = public, extensions
as $$
declare
  v_terms text[];
begin
  select coalesce(array_agg(t order by first_pos), '{}')
    into v_terms
    from (
      select t, min(ord) as first_pos
        from (
          select btrim(regexp_replace(lower(public.xah_unaccent(x)), '\s+', ' ', 'g')) as t, ord
            from unnest(new.terms) with ordinality as u(x, ord)
        ) n
       where t <> ''
       group by t
    ) d;

  if cardinality(v_terms) < 2 then
    raise exception 'Un grupo de sinónimos necesita al menos dos términos distintos.' using errcode = '22023';
  end if;
  if cardinality(v_terms) > 14 then
    raise exception 'Un grupo de sinónimos admite hasta 14 términos.' using errcode = '22023';
  end if;
  if exists (select 1 from unnest(v_terms) t where char_length(t) < 2 or char_length(t) > 40) then
    raise exception 'Cada término tiene entre 2 y 40 letras.' using errcode = '22023';
  end if;

  new.terms := v_terms;
  return new;
end;
$$;

drop trigger if exists search_synonym_groups_normalize_trg on public.search_synonym_groups;
create trigger search_synonym_groups_normalize_trg
  before insert or update of terms on public.search_synonym_groups
  for each row execute function public.search_synonym_groups_normalize();

alter table public.search_synonym_groups enable row level security;

drop policy if exists "los sinonimos los lee cualquiera" on public.search_synonym_groups;
create policy "los sinonimos los lee cualquiera"
  on public.search_synonym_groups for select using (true);

drop policy if exists "un admin escribe sinonimos" on public.search_synonym_groups;
create policy "un admin escribe sinonimos"
  on public.search_synonym_groups for all
  using (public.is_admin())
  with check (public.is_admin());

revoke insert, update, delete on public.search_synonym_groups from anon;


-- -----------------------------------------------------------------------------
-- 2. Expansión de una palabra
-- -----------------------------------------------------------------------------

-- Los términos de todo grupo al que pertenece la palabra (ella incluida). Un grupo "contiene" la palabra si la trae completa o,
-- desde 4 letras, si la palabra es el comienzo de un término ("bump" → bumper): así se entiende lo que se está tecleando.
create or replace function public.xah_synonyms(p_word text)
returns text[]
language sql
stable
set search_path = public, extensions
as $$
  select coalesce(array_agg(distinct x), '{}')
    from public.search_synonym_groups g
   cross join lateral unnest(g.terms) as x
   where char_length(coalesce(p_word, '')) >= 2
     and exists (
       select 1
         from unnest(g.terms) t
        where t = p_word
           or (char_length(p_word) >= 4 and starts_with(t, p_word))
     );
$$;

-- Cada palabra útil de la consulta con su tsquery: la palabra con prefijo OR cada sinónimo exacto (los de varias palabras, como frase).
-- Las palabras vacías ("de", "para") no producen nada y se descartan, igual que antes.
create or replace function public.xah_query_words(p_query text)
returns table (word text, wq tsquery)
language plpgsql
stable
set search_path = public, extensions
as $$
declare
  w     text;
  t     text;
  expr  text;
  parts text[];
  q     tsquery;
begin
  for w in
    select d.word
      from (
        select regexp_replace(tk.tok, '[^a-z0-9]', '', 'g') as word, min(tk.ord) as ord
          from unnest(regexp_split_to_array(lower(public.xah_unaccent(btrim(coalesce(p_query, '')))), '\s+')) with ordinality as tk(tok, ord)
         group by 1
      ) d
     where d.word <> ''
     order by d.ord
     limit 8
  loop
    expr := w || ':*';
    foreach t in array public.xah_synonyms(w) loop
      continue when t = w;
      parts := array(
        select regexp_replace(x, '[^a-z0-9]', '', 'g')
          from unnest(string_to_array(t, ' ')) x
         where regexp_replace(x, '[^a-z0-9]', '', 'g') <> ''
      );
      continue when cardinality(parts) = 0;
      expr := expr || ' | ' || array_to_string(parts, ' <-> ');
    end loop;

    q := to_tsquery('spanish', expr);
    if numnode(q) > 0 then
      word := w;
      wq := q;
      return next;
    end if;
  end loop;
end;
$$;

comment on function public.xah_query_words(text) is
  'Las palabras de una búsqueda con su tsquery expandido a sinónimos. Lo usa search_products().';

-- Escapa \, % y _ de un texto para usarlo como patrón de LIKE.
create or replace function public.xah_like_escape(p_text text)
returns text
language sql
immutable
as $$
  select replace(replace(replace(coalesce(p_text, ''), '\', '\\'), '%', '\%'), '_', '\_');
$$;


-- -----------------------------------------------------------------------------
-- 3. search_products()
-- -----------------------------------------------------------------------------
-- Misma firma y mismas columnas que la 0023 (con el número de parte de la 0051): `create or replace` conserva los permisos.

create or replace function public.search_products(
  p_query         text    default null,
  p_category_slug text    default null,
  p_make_id       bigint  default null,
  p_model_id      bigint  default null,
  p_year          integer default null,
  p_min_price     numeric default null,
  p_max_price     numeric default null,
  p_in_stock_only boolean default false,
  p_sort          text    default 'relevance',
  p_limit         integer default 24,
  p_offset        integer default 0
)
returns table (
  id                      bigint,
  category_id             bigint,
  slug                    text,
  sku                     text,
  name                    text,
  brand                   text,
  short_description       text,
  img_url                 text,
  images                  text[],
  stars_rating            numeric,
  price                   numeric,
  compare_at_price        numeric,
  description             text,
  stock                   integer,
  is_active               boolean,
  is_test                 boolean,
  is_featured             boolean,
  fulfillment             public.product_fulfillment,
  lead_time_days          integer,
  fitment_type            public.product_fitment_type,
  installable             boolean,
  installation_service_id bigint,
  specs                   jsonb,
  sold_count              integer,
  created_at              timestamptz,
  updated_at              timestamptz,
  has_variants            boolean,
  variant_label           text,
  total_count             bigint
)
language sql
stable
security invoker
set search_path = public, extensions
as $$
  with q as (
    select
      nullif(btrim(coalesce(p_query, '')), '') as raw,
      -- Patrón para el like: se escapan \, % y _ para que "100%" no sea comodín.
      '%' || public.xah_like_escape(coalesce(public.xah_unaccent(nullif(btrim(coalesce(p_query, '')), '')), '')) || '%' as pat,
      public.xah_norm_part(p_query) as part
  ),
  words as materialized (
    select * from public.xah_query_words(p_query)
  ),
  filtered as (
    select
      p.*,
      (
        -- Cuánto dice el producto de lo que se busca: el nombre pesa más que la categoría o la descripción.
        (select coalesce(sum(ts_rank(x.doc, w.wq)), 0) from words w)
        + (select count(*) from words w where x.name_vec @@ w.wq)
        + 0.5 * (select count(*) from words w where x.alias_vec @@ w.wq)
        + case when q.part <> '' and (p.part_number_norm = q.part or p.cross_refs_norm @> array[q.part]) then 10 else 0 end
      ) as rnk
    from public.hub_parts p
    cross join q
    cross join lateral (
      select
        p.search_vector
          || to_tsvector('spanish', public.xah_unaccent(coalesce(c.name, '') || ' ' || coalesce(pc.name, '')))
          || to_tsvector('spanish', public.xah_unaccent(coalesce(al.txt, ''))) as doc,
        to_tsvector('spanish', public.xah_unaccent(p.name)) as name_vec,
        to_tsvector('spanish', public.xah_unaccent(coalesce(al.txt, ''))) as alias_vec
        from (select 1) one
        left join public.product_categories c on c.id = p.category_id
        left join public.product_categories pc on pc.id = c.parent_id
        left join lateral (
          select string_agg(a.alias, ' ') as txt from public.product_aliases a where a.product_id = p.id
        ) al on true
    ) x
    where p.is_active
      and (
        q.raw is null
        -- Cada palabra tiene que estar (con sus sinónimos) o ser un error de tecleo evidente de la marca o del nombre.
        or (
          exists (select 1 from words)
          and not exists (
            select 1
              from words w
             where not (
               x.doc @@ w.wq
               or (
                 char_length(w.word) >= 5
                 and (
                   word_similarity(w.word, lower(public.xah_unaccent(p.name))) >= 0.6
                   or similarity(lower(public.xah_unaccent(p.brand)), w.word) >= 0.35
                 )
               )
             )
          )
        )
        or public.xah_unaccent(p.name)  ilike q.pat
        or public.xah_unaccent(p.brand) ilike q.pat
        or p.sku ilike q.pat
        or (q.part <> '' and (p.part_number_norm = q.part or p.cross_refs_norm @> array[q.part]))
      )
      and (
        p_category_slug is null
        or p.category_id in (
          select c.id
            from public.product_categories c
           where c.slug = p_category_slug
              or c.parent_id = (select r.id from public.product_categories r where r.slug = p_category_slug)
        )
      )
      and (
        p_make_id is null
        or p.fitment_type = 'universal'
        or exists (
          select 1
            from public.product_fitments f
           where f.product_id = p.id
             and f.make_id = p_make_id
             -- Sin modelo elegido basta con la marca; con modelo, el fitment es
             -- de toda la marca (model_id nulo) o de ese modelo.
             and (p_model_id is null or f.model_id is null or f.model_id = p_model_id)
             and (p_year is null or f.year_from is null or f.year_from <= p_year)
             and (p_year is null or f.year_to   is null or f.year_to   >= p_year)
        )
      )
      and (p_min_price is null or p.price >= p_min_price)
      and (p_max_price is null or p.price <= p_max_price)
      and (not coalesce(p_in_stock_only, false) or (p.fulfillment = 'stock' and p.stock > 0))
  )
  select
    f.id, f.category_id, f.slug, f.sku, f.name, f.brand,
    f.short_description, f.img_url, f.images, f.stars_rating, f.price,
    f.compare_at_price, f.description, f.stock, f.is_active, f.is_test,
    f.is_featured, f.fulfillment, f.lead_time_days, f.fitment_type,
    f.installable, f.installation_service_id, f.specs, f.sold_count,
    f.created_at, f.updated_at, f.has_variants, f.variant_label,
    count(*) over () as total_count
  from filtered f
  order by
    case when p_sort = 'price_asc'     then f.price      end asc,
    case when p_sort = 'price_desc'    then f.price      end desc,
    case when p_sort = 'best_sellers'  then f.sold_count end desc,
    case when p_sort = 'newest'        then f.created_at end desc,
    case when coalesce(p_sort, 'relevance')
              not in ('price_asc', 'price_desc', 'best_sellers', 'newest')
         then f.rnk end desc,
    f.is_featured desc,
    f.sold_count desc,
    f.id
  limit  least(greatest(coalesce(p_limit, 24), 1), 100)
  offset greatest(coalesce(p_offset, 0), 0);
$$;

