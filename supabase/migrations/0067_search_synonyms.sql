-- -----------------------------------------------------------------------------
-- 4. suggest_products()
-- -----------------------------------------------------------------------------
-- Mismo contrato (columnas y permisos) que la 0048 con el número de parte de la 0051. Cambia el puntaje: sinónimos y categoría suman,
-- y la similitud por trigramas solo cuenta si es evidente (el "front mount" de "fren").

create or replace function public.suggest_products(
  p_query text,
  p_limit integer default 6
)
returns table (
  id            bigint,
  slug          text,
  name          text,
  brand         text,
  img_url       text,
  price         numeric,
  stock         integer,
  fulfillment   public.product_fulfillment,
  matched_alias text,
  score         real
)
language sql
stable
security invoker
set search_path = public, extensions
as $$
  with q as (
    select
      n.norm,
      public.xah_norm_part(p_query) as part,
      -- Lo que se escribió y sus sinónimos, como patrones de prefijo ya escapados. El primero es lo que se escribió.
      array(
        select public.xah_like_escape(t.term) || '%'
          from unnest(array[n.norm] || public.xah_synonyms(n.norm)) with ordinality as t(term, ord)
         where t.term <> '' and (t.ord = 1 or t.term <> n.norm)
         order by t.ord
      ) as pfx
    from (select lower(public.xah_unaccent(btrim(coalesce(p_query, '')))) as norm) n
  ),
  scored as (
    select
      p.id, p.slug, p.name, p.brand, p.img_url, p.price, p.stock, p.fulfillment, p.is_featured, p.sold_count,
      -- El mejor alias, solo si le gana al nombre.
      (
        select a.alias
          from public.product_aliases a
         where a.product_id = p.id
           and (
             lower(public.xah_unaccent(a.alias)) like any (q.pfx)
             or lower(public.xah_unaccent(a.alias)) like any (array(select '% ' || x from unnest(q.pfx) x))
             or similarity(lower(public.xah_unaccent(a.alias)), q.norm) > 0.3
           )
         order by similarity(lower(public.xah_unaccent(a.alias)), q.norm) desc, a.id
         limit 1
      ) as alias_hit,
      greatest(
        -- Empieza igual: lo más relevante. Un sinónimo vale un poco menos que lo escrito.
        coalesce((
          select max(
                   (case
                      when lower(public.xah_unaccent(p.name))  like pf.x then 1.0
                      when lower(public.xah_unaccent(p.brand)) like pf.x then 0.9
                      -- Una palabra del nombre empieza igual ("frenos" en "Discos de frenos").
                      when lower(public.xah_unaccent(p.name))  like '% ' || pf.x then 0.8
                      -- La categoría (y la del padre): "frenos" encuentra los discos aunque el nombre no lo diga.
                      when lower(public.xah_unaccent(c.name))  like pf.x or lower(public.xah_unaccent(c.name))  like '% ' || pf.x
                        or lower(public.xah_unaccent(pc.name)) like pf.x or lower(public.xah_unaccent(pc.name)) like '% ' || pf.x then 0.55
                      else 0
                    end) * (case when pf.ord = 1 then 1.0 else 0.92 end)
                 )
            from unnest(q.pfx) with ordinality as pf(x, ord)
        ), 0),
        case when p.sku ilike q.pfx[1] then 0.9 else 0 end,
        case when q.part <> '' and (p.part_number_norm = q.part or p.cross_refs_norm @> array[q.part]) then 1.0 else 0 end,
        -- Errores de tecleo: solo con 4 letras o más y una similitud evidente (con menos, "fren" coincidía con "front").
        case when char_length(q.norm) >= 4 and word_similarity(q.norm, lower(public.xah_unaccent(p.name))) >= 0.6
             then 0.85 * word_similarity(q.norm, lower(public.xah_unaccent(p.name))) else 0 end,
        -- La marca también perdona errores de tecleo ("brenbo" → Brembo).
        case when char_length(q.norm) >= 4 then 0.9 * similarity(lower(public.xah_unaccent(p.brand)), q.norm) else 0 end
      ) as name_score
    from public.hub_parts p
    cross join q
    left join public.product_categories c on c.id = p.category_id
    left join public.product_categories pc on pc.id = c.parent_id
    where p.is_active
      and char_length(q.norm) >= 2
  )
  select
    s.id, s.slug, s.name, s.brand, s.img_url, s.price, s.stock, s.fulfillment,
    case when s.name_score >= 0.5 then null else s.alias_hit end as matched_alias,
    greatest(
      s.name_score,
      case when s.alias_hit is not null then 0.6 else 0 end
    )::real as score
  from scored s
  where s.name_score >= 0.3 or s.alias_hit is not null
  order by score desc, s.is_featured desc, s.sold_count desc, s.name
  limit greatest(1, least(coalesce(p_limit, 6), 20));
$$;

