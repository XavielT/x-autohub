-- =============================================================================
-- 0045 — Comunidad: me gusta, comentarios y fotos/video en el feed
-- =============================================================================
-- Hasta ahora `social_posts.likes` y `.comments` eran números sembrados que nadie movía, y una
-- publicación solo podía llevar una imagen. Esta migración los vuelve de verdad:
--
--   1. `social_posts.media` (jsonb): hasta 4 archivos por publicación, cada uno
--      `{ "type": "image" | "video", "url": "…" }`. `image_url` se queda para lo sembrado.
--   2. `social_post_likes`: un me gusta por persona y publicación (PK compuesta). Cada quien
--      solo ve y toca los suyos; el número que todos ven sale de `social_posts.likes`.
--   3. `social_post_comments`: públicos de lectura; escribe quien tenga sesión; borra su autor
--      o un admin.
--   4. Dos triggers (security definer) mantienen `likes` y `comments`. Para que nadie se
--      escriba sus propios números, se le quita a `authenticated` el UPDATE de esas dos
--      columnas (y de las demás que no edita una persona) y solo se le devuelve lo editable.
--   5. El bucket `social-media`: fotos (JPG, PNG, WebP) y video (MP4, WebM) de hasta 25 MB.
--      Como en `listings`, la primera carpeta de la ruta es el uid de quien sube.
--
-- ORDEN DE DESPLIEGUE: primero esta migración, después el frontend. El frontend anterior no
-- toca nada de esto y sigue funcionando.
--
-- Se puede ejecutar dos veces: `if not exists`, `drop … if exists`, `create or replace`.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. Media de la publicación
-- -----------------------------------------------------------------------------

alter table public.social_posts
  add column if not exists media jsonb not null default '[]'::jsonb;

do $$
begin
  alter table public.social_posts
    add constraint social_posts_media_check
    check (jsonb_typeof(media) = 'array' and jsonb_array_length(media) <= 4);
exception when duplicate_object then null;
end
$$;

comment on column public.social_posts.media is
  'Hasta 4 archivos: [{"type":"image"|"video","url":"…"}]. image_url queda para lo sembrado.';


-- -----------------------------------------------------------------------------
-- 2. Me gusta
-- -----------------------------------------------------------------------------

create table if not exists public.social_post_likes (
  post_id    bigint      not null references public.social_posts(id) on delete cascade,
  user_id    uuid        not null references public.profiles(id)     on delete cascade,
  created_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

create index if not exists social_post_likes_user_idx on public.social_post_likes (user_id);

comment on table public.social_post_likes is
  'Un me gusta por persona y publicación. Cada quien ve solo los suyos; el total público es social_posts.likes.';

alter table public.social_post_likes enable row level security;

drop policy if exists "cada quien ve sus me gusta" on public.social_post_likes;
create policy "cada quien ve sus me gusta"
  on public.social_post_likes for select
  to authenticated
  using (user_id = auth.uid());

drop policy if exists "cada quien da su me gusta" on public.social_post_likes;
create policy "cada quien da su me gusta"
  on public.social_post_likes for insert
  to authenticated
  with check (user_id = auth.uid());

drop policy if exists "cada quien quita su me gusta" on public.social_post_likes;
create policy "cada quien quita su me gusta"
  on public.social_post_likes for delete
  to authenticated
  using (user_id = auth.uid());

-- Sin sesión no hay me gusta, y no se edita (se da o se quita).
revoke all on public.social_post_likes from anon;
revoke update on public.social_post_likes from authenticated;


-- -----------------------------------------------------------------------------
-- 3. Comentarios
-- -----------------------------------------------------------------------------

create table if not exists public.social_post_comments (
  id         bigint generated by default as identity primary key,
  post_id    bigint      not null references public.social_posts(id) on delete cascade,
  author_id  uuid        not null references public.profiles(id)     on delete cascade,
  text       text        not null
               check (text = btrim(text) and char_length(text) between 1 and 500),
  created_at timestamptz not null default now()
);

create index if not exists social_post_comments_post_idx
  on public.social_post_comments (post_id, created_at);

comment on table public.social_post_comments is
  'Comentarios de una publicación del feed: de 1 a 500 caracteres. Públicos de lectura.';

alter table public.social_post_comments enable row level security;

drop policy if exists "los comentarios los ve todo el mundo" on public.social_post_comments;
create policy "los comentarios los ve todo el mundo"
  on public.social_post_comments for select
  using (true);

drop policy if exists "quien tiene sesion comenta" on public.social_post_comments;
create policy "quien tiene sesion comenta"
  on public.social_post_comments for insert
  to authenticated
  with check (author_id = auth.uid());

drop policy if exists "el autor o un admin borra el comentario" on public.social_post_comments;
create policy "el autor o un admin borra el comentario"
  on public.social_post_comments for delete
  to authenticated
  using (author_id = auth.uid() or public.is_admin());

-- Un comentario no se edita: se borra y se vuelve a escribir.
revoke insert, update, delete on public.social_post_comments from anon;
revoke update on public.social_post_comments from authenticated;


-- -----------------------------------------------------------------------------
-- 4. Los contadores los mueven los triggers, no el navegador
-- -----------------------------------------------------------------------------

create or replace function public.social_post_likes_count()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    update public.social_posts set likes = likes + 1 where id = new.post_id;
    return new;
  end if;
  update public.social_posts set likes = greatest(likes - 1, 0) where id = old.post_id;
  return old;
end;
$$;

create or replace function public.social_post_comments_count()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    update public.social_posts set comments = comments + 1 where id = new.post_id;
    return new;
  end if;
  update public.social_posts set comments = greatest(comments - 1, 0) where id = old.post_id;
  return old;
end;
$$;

-- Funciones de trigger: no se llaman a mano. Las tres líneas de siempre.
revoke all on function public.social_post_likes_count()    from public, anon, authenticated;
revoke all on function public.social_post_comments_count() from public, anon, authenticated;

drop trigger if exists social_post_likes_count on public.social_post_likes;
create trigger social_post_likes_count
  after insert or delete on public.social_post_likes
  for each row execute function public.social_post_likes_count();

drop trigger if exists social_post_comments_count on public.social_post_comments;
create trigger social_post_comments_count
  after insert or delete on public.social_post_comments
  for each row execute function public.social_post_comments_count();

-- Quien escribe una publicación no se pone sus propios me gusta: el UPDATE de `authenticated`
-- queda solo en lo que una persona edita de su publicación. (Los triggers de arriba corren como
-- el dueño de la función y no dependen de este permiso.)
revoke update on public.social_posts from authenticated;
grant update (text, image_url, tags, author_club, media) on public.social_posts to authenticated;


-- -----------------------------------------------------------------------------
-- 5. Storage: fotos y video de la comunidad
-- -----------------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'social-media', 'social-media', true, 26214400,
  array['image/jpeg', 'image/png', 'image/webp', 'video/mp4', 'video/webm']
)
on conflict (id) do update
  set public             = excluded.public,
      file_size_limit    = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "los archivos de la comunidad los ve todo el mundo" on storage.objects;
create policy "los archivos de la comunidad los ve todo el mundo"
  on storage.objects for select
  using (bucket_id = 'social-media');

drop policy if exists "cada quien sube a su carpeta de la comunidad" on storage.objects;
create policy "cada quien sube a su carpeta de la comunidad"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'social-media'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "cada quien borra sus archivos de la comunidad" on storage.objects;
create policy "cada quien borra sus archivos de la comunidad"
  on storage.objects for delete
  to authenticated
  using (
    bucket_id = 'social-media'
    and (storage.foldername(name))[1] = auth.uid()::text
  );
