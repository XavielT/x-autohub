-- =============================================================================
-- 0042 — Sugerencias del buscador: trigramas y alias
-- =============================================================================
-- El cuadro de búsqueda pedía sus sugerencias a `search_products()`, que es la búsqueda
-- completa (total_count, filtros, orden). Para teclear "frenos" o "bocinas" basta mucho menos,
-- y tiene que perdonar errores de tecleo ("brembo" → "brenbo") y entender cómo habla la gente
-- ("bumper" por "parachoques").
--
--   1. `product_aliases`: otros nombres con los que alguien buscaría un producto. Los escribe
--      un admin desde el panel (Inventario → Alias de búsqueda). Públicos de lectura: no tienen
--      nada sensible, y la búsqueda corre como quien llama (security invoker).
--   2. `suggest_products(p_query, p_limit)`: una consulta pequeña. Coincide por prefijo del
--      nombre/marca/SKU, por similitud de trigramas (pg_trgm) o por un alias, y devuelve el
--      alias que coincidió para que la interfaz diga "también: bumper".
--
-- ORDEN DE DESPLIEGUE: primero esta migración, después el frontend (el frontend anterior
-- no la conoce y sigue usando `search_products()`; el nuevo cae a `search_products()` si la
-- función no existe todavía).
--
-- Se puede ejecutar dos veces: todo lleva `if not exists` / `create or replace`.
-- =============================================================================

create extension if not exists pg_trgm with schema extensions;


-- -----------------------------------------------------------------------------
-- 1. Alias
-- -----------------------------------------------------------------------------

create table if not exists public.product_aliases (
  id         bigint generated by default as identity primary key,
  product_id bigint not null references public.hub_parts(id) on delete cascade,
  alias      text   not null
               check (alias = btrim(alias) and char_length(alias) between 2 and 60),
  created_at timestamptz not null default now()
);

-- El mismo alias dos veces en un producto no aporta nada (sin distinguir mayúsculas ni tildes).
create unique index if not exists product_aliases_unique
  on public.product_aliases (product_id, lower(public.xah_unaccent(alias)));
create index if not exists product_aliases_product_idx
  on public.product_aliases (product_id);
create index if not exists product_aliases_trgm_idx
  on public.product_aliases using gin (lower(public.xah_unaccent(alias)) extensions.gin_trgm_ops);

-- Trigramas sobre lo que se busca de un producto.
create index if not exists hub_parts_name_trgm_idx
  on public.hub_parts using gin (lower(public.xah_unaccent(name)) extensions.gin_trgm_ops);

comment on table public.product_aliases is
  'Otros nombres con los que se busca un producto ("bumper" para un parachoques). Los administra un admin.';

alter table public.product_aliases enable row level security;

-- Se ven los alias de los productos que quien llama ve (el exists aplica el RLS de hub_parts:
-- el alias de un producto de prueba o apagado no sale).
drop policy if exists "los alias los ve quien ve el producto" on public.product_aliases;
create policy "los alias los ve quien ve el producto"
  on public.product_aliases for select
  using (exists (select 1 from public.hub_parts p where p.id = product_aliases.product_id));

drop policy if exists "un admin escribe alias" on public.product_aliases;
create policy "un admin escribe alias"
  on public.product_aliases for all
  using (public.is_admin())
  with check (public.is_admin());

revoke insert, update, delete on public.product_aliases from anon;


-- -----------------------------------------------------------------------------
-- 2. suggest_products()
-- -----------------------------------------------------------------------------
-- Devuelve lo mínimo que pinta una sugerencia. `matched_alias` viene lleno solo cuando fue un
-- alias lo que coincidió y el nombre no (si coinciden los dos, no hay nada que explicar).

create or replace function public.suggest_products(
  p_query text,
  p_limit integer default 6
)
returns table (
  id            bigint,
  slug          text,
  name          text,
  brand         text,
  img_url       text,
  price         numeric,
  stock         integer,
  fulfillment   public.product_fulfillment,
  matched_alias text,
  score         real
)
language sql
stable
security invoker
set search_path = public, extensions
as $$
  with q as (
    select
      lower(public.xah_unaccent(btrim(coalesce(p_query, '')))) as norm,
      -- Patrón de prefijo, con \, % y _ escapados para que "100%" no sea comodín.
      replace(replace(replace(
        lower(public.xah_unaccent(btrim(coalesce(p_query, '')))),
        '\', '\\'), '%', '\%'), '_', '\_') || '%' as prefix
  ),
  scored as (
    select
      p.id, p.slug, p.name, p.brand, p.img_url, p.price, p.stock, p.fulfillment,
      -- El mejor alias, solo si le gana al nombre.
      (
        select a.alias
          from public.product_aliases a
         where a.product_id = p.id
           and (
             lower(public.xah_unaccent(a.alias)) like q.prefix
             or lower(public.xah_unaccent(a.alias)) like '% ' || q.prefix
             or similarity(lower(public.xah_unaccent(a.alias)), q.norm) > 0.3
           )
         order by similarity(lower(public.xah_unaccent(a.alias)), q.norm) desc, a.id
         limit 1
      ) as alias_hit,
      greatest(
        -- Empieza igual: lo más relevante.
        case when lower(public.xah_unaccent(p.name))  like q.prefix then 1.0 else 0 end,
        case when lower(public.xah_unaccent(p.brand)) like q.prefix then 0.9 else 0 end,
        case when p.sku ilike q.prefix                              then 0.9 else 0 end,
        -- Una palabra del nombre empieza igual ("frenos" en "Discos de frenos").
        case when lower(public.xah_unaccent(p.name)) like '% ' || q.prefix then 0.8 else 0 end,
        similarity(lower(public.xah_unaccent(p.name)), q.norm),
        word_similarity(q.norm, lower(public.xah_unaccent(p.name)))
      ) as name_score
    from public.hub_parts p
    cross join q
    where p.is_active
      and char_length(q.norm) >= 2
  )
  select
    s.id, s.slug, s.name, s.brand, s.img_url, s.price, s.stock, s.fulfillment,
    case when s.name_score >= 0.5 then null else s.alias_hit end as matched_alias,
    greatest(
      s.name_score,
      case when s.alias_hit is not null then 0.6 else 0 end
    )::real as score
  from scored s
  where s.name_score >= 0.3 or s.alias_hit is not null
  order by score desc, s.name
  limit greatest(1, least(coalesce(p_limit, 6), 20));
$$;

comment on function public.suggest_products(text, integer) is
  'Sugerencias del buscador: prefijo, trigramas y alias. matched_alias dice qué alias coincidió cuando el nombre no. security invoker: RLS decide qué ve quien llama.';

revoke all on function public.suggest_products(text, integer) from public;
grant execute on function public.suggest_products(text, integer) to anon, authenticated;
