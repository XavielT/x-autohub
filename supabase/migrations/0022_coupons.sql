-- =============================================================================
-- X AutoHub — Cupones y descuentos (después del pivote)
-- =============================================================================
--
-- Un cliente escribe un código en el checkout y el pedido sale con descuento. Tres
-- tipos:
--
--   · `percent`       un porcentaje del subtotal (con un tope opcional en RD$).
--   · `fixed`         un monto fijo en RD$ sobre el subtotal.
--   · `free_shipping` el envío gratis (descuenta el envío, no el subtotal).
--
-- y las condiciones que un comercio pide: compra mínima, vigencia (desde / hasta),
-- cuántas veces se puede usar en total y cuántas por cliente.
--
--
-- LO QUE SE DECIDIÓ
-- ------------------
-- · **El descuento lo calcula Postgres, nunca el navegador**, igual que el precio y el
--   envío. `create_order()` recibe solo el código y lo revalida dentro de la
--   transacción; `validate_coupon()` es la misma regla para enseñar el descuento antes
--   de confirmar (y la puede invocar un invitado, porque el checkout de invitado existe).
--
-- · **La tabla `coupons` NO se puede leer con la clave anon**: si se pudiera, cualquiera
--   descargaría todos los códigos. Solo la lee y la escribe un admin; el público solo
--   los conoce si se los dan y los prueba con `validate_coupon()`.
--
-- · **Los usos se cuentan, no se guardan en un contador**: son los pedidos con ese
--   cupón que no están cancelados. Así cancelar un pedido devuelve el uso sin ningún
--   trigger, y el número nunca se desincroniza. Para que dos pedidos simultáneos no se
--   lleven el último uso, `create_order()` bloquea la fila del cupón (`for update`)
--   antes de contar.
--
-- · **El límite por cliente identifica a la persona** por su cuenta (`user_id`) o, si
--   compra de invitado, por su correo. Un invitado puede cambiar de correo: es un tope
--   de cortesía, no una barrera contra el abuso; para eso está `max_uses`.
--
-- · **Los mensajes de error no distinguen "no existe" de "ya venció o está apagado"**:
--   quien prueba códigos al azar no aprende cuáles existen. Los que sí son específicos
--   (compra mínima, ya lo usaste, agotado) solo salen con un código que existe y
--   cumple, y dicen lo que la persona puede hacer.
--
-- · **Un descuento nunca deja el total en negativo**: se limita al subtotal (o al envío,
--   en `free_shipping`). Un cupón que no descuenta nada (`free_shipping` en un retiro)
--   se rechaza: "no aplica a tu pedido".
--
--
-- ORDEN DE DESPLIEGUE
-- -------------------
-- **Primero esta migración, después el frontend.** `create_order()` gana un parámetro al
-- final con valor por defecto, y se retira la firma anterior (dejarla viva haría que
-- PostgREST respondiera PGRST203 ante cualquier llamada). El frontend anterior sigue
-- funcionando contra la función nueva (no manda el parámetro nuevo); el frontend nuevo
-- NO funcionaría contra la vieja (le mandaría `p_coupon_code`).
--
--
-- ESTA MIGRACIÓN SE PUEDE EJECUTAR DOS VECES
-- ------------------------------------------
-- Todo lleva `if not exists` / `create or replace` / `drop ... if exists`.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. La tabla
-- -----------------------------------------------------------------------------

do $$
begin
  create type public.coupon_type as enum ('percent', 'fixed', 'free_shipping');
exception when duplicate_object then null;
end
$$;

create table if not exists public.coupons (
  id                     bigint generated by default as identity primary key,
  -- Siempre en mayúsculas y sin espacios: se compara tal cual. Lo que escriba el cliente
  -- se pasa a mayúsculas antes de buscarlo.
  code                   text not null
                           check (code = upper(btrim(code)) and code ~ '^[A-Z0-9_-]{4,32}$'),
  description            text not null default '',
  discount_type          public.coupon_type not null,
  -- percent: 1 a 100. fixed: RD$ mayor que 0. free_shipping: nulo.
  discount_value         numeric(12,2),
  -- Compra mínima (subtotal) para poder usarlo.
  min_subtotal           numeric(12,2) not null default 0 check (min_subtotal >= 0),
  -- Tope del descuento en RD$ (solo tiene sentido en percent). Nulo = sin tope.
  max_discount           numeric(12,2) check (max_discount is null or max_discount > 0),
  starts_at              timestamptz,
  ends_at                timestamptz,
  -- Nulo = sin límite.
  max_uses               integer check (max_uses is null or max_uses > 0),
  max_uses_per_customer  integer check (max_uses_per_customer is null or max_uses_per_customer > 0),
  is_active              boolean not null default true,
  created_at             timestamptz not null default now(),

  constraint coupons_value_matches_type check (
    (discount_type = 'percent'       and discount_value is not null and discount_value > 0 and discount_value <= 100)
    or (discount_type = 'fixed'      and discount_value is not null and discount_value > 0)
    or (discount_type = 'free_shipping' and discount_value is null)
  ),
  constraint coupons_dates_in_order check (starts_at is null or ends_at is null or ends_at > starts_at)
);

create unique index if not exists coupons_code_key on public.coupons (code);

comment on table public.coupons is
  'Cupones de descuento. Solo un admin la lee y la escribe; el público los prueba con validate_coupon().';

alter table public.coupons enable row level security;

drop policy if exists "solo admin gestiona los cupones" on public.coupons;
create policy "solo admin gestiona los cupones"
  on public.coupons for all
  using (public.is_admin())
  with check (public.is_admin());

-- Defensa en profundidad: los default privileges de Supabase le dan todo a `anon` sobre
-- las tablas nuevas y solo RLS lo detiene. Con los códigos de descuento en juego, se le
-- quita también el permiso de tabla.
revoke all on public.coupons from anon;


-- -----------------------------------------------------------------------------
-- 2. El pedido recuerda el cupón
-- -----------------------------------------------------------------------------
-- `coupon_code` es una copia: si el cupón se borra o se edita, el pedido sigue diciendo
-- con cuál se compró. `total = subtotal + shipping_price - discount`.

alter table public.orders
  add column if not exists coupon_id   bigint references public.coupons(id) on delete set null,
  add column if not exists coupon_code text,
  add column if not exists discount    numeric(12,2) not null default 0;

do $$
begin
  alter table public.orders
    add constraint orders_discount_check check (discount >= 0);
exception when duplicate_object then null;
end
$$;

create index if not exists orders_coupon_idx on public.orders (coupon_id) where coupon_id is not null;

comment on column public.orders.discount is
  'Descuento aplicado (RD$). total = subtotal + shipping_price - discount.';


-- -----------------------------------------------------------------------------
-- 3. La regla: coupon_check()
-- -----------------------------------------------------------------------------
-- Una sola función para las dos puertas (previsualizar y crear el pedido), así lo que
-- se le enseña a quien compra y lo que se cobra no pueden diferir. No la llama el
-- navegador: la invocan `validate_coupon()` y `create_order()`.
--
-- `p_lock`: al crear el pedido se bloquea la fila del cupón antes de contar los usos.

create or replace function public.coupon_check(
  p_code      text,
  p_subtotal  numeric,
  p_shipping  numeric,
  p_email     text,
  p_user_id   uuid,
  p_lock      boolean
)
returns table (
  coupon_id     bigint,
  code          text,
  discount_type public.coupon_type,
  discount      numeric,
  description   text
)
language plpgsql
security definer
set search_path = public
as $$
#variable_conflict use_column
declare
  v_code     text := upper(btrim(coalesce(p_code, '')));
  c          public.coupons%rowtype;
  v_discount numeric(12,2);
  v_uses     integer;
  v_mine     integer;
begin
  if v_code = '' then
    raise exception 'Escribe el codigo del cupon.' using errcode = '22023';
  end if;

  if p_lock then
    select * into c from public.coupons x where x.code = v_code for update;
  else
    select * into c from public.coupons x where x.code = v_code;
  end if;

  -- No existe, está apagado o fuera de fecha: el mismo mensaje (ver la cabecera).
  if not found
     or not c.is_active
     or (c.starts_at is not null and now() < c.starts_at)
     or (c.ends_at   is not null and now() >= c.ends_at) then
    raise exception 'Ese cupon no existe o ya no esta disponible.' using errcode = '22023';
  end if;

  if p_subtotal < c.min_subtotal then
    raise exception 'Este cupon pide una compra de al menos RD$ %.', to_char(c.min_subtotal, 'FM999,999,990')
      using errcode = '22023';
  end if;

  if c.max_uses is not null then
    select count(*) into v_uses
    from public.orders o
    where o.coupon_id = c.id and o.status <> 'cancelled';

    if v_uses >= c.max_uses then
      raise exception 'Este cupon ya se agoto.' using errcode = '22023';
    end if;
  end if;

  if c.max_uses_per_customer is not null then
    select count(*) into v_mine
    from public.orders o
    where o.coupon_id = c.id
      and o.status <> 'cancelled'
      and (
        (p_user_id is not null and o.user_id = p_user_id)
        or (coalesce(btrim(p_email), '') <> '' and lower(o.contact_email) = lower(btrim(p_email)))
      );

    if v_mine >= c.max_uses_per_customer then
      raise exception 'Ya usaste este cupon.' using errcode = '22023';
    end if;
  end if;

  -- El descuento. Nunca deja el total en negativo.
  v_discount := case c.discount_type
    when 'percent' then
      least(
        round(p_subtotal * c.discount_value / 100, 2),
        coalesce(c.max_discount, round(p_subtotal * c.discount_value / 100, 2)),
        p_subtotal
      )
    when 'fixed' then
      least(c.discount_value, p_subtotal)
    else
      greatest(coalesce(p_shipping, 0), 0)
  end;

  if v_discount <= 0 then
    raise exception 'Este cupon no aplica a tu pedido.' using errcode = '22023';
  end if;

  return query select c.id, c.code, c.discount_type, v_discount, c.description;
end;
$$;

comment on function public.coupon_check(text, numeric, numeric, text, uuid, boolean) is
  'La regla de un cupon: vigencia, compra minima, usos y descuento. La invocan validate_coupon() y create_order(), no el navegador.';

-- Interna: solo la invocan otras funciones `security definer` del mismo dueño.
revoke all on function public.coupon_check(text, numeric, numeric, text, uuid, boolean)
  from public, anon, authenticated;


-- -----------------------------------------------------------------------------
-- 4. validate_coupon(): previsualizar el descuento
-- -----------------------------------------------------------------------------
-- La invoca el checkout al aplicar el código, y otra vez si cambia el envío o el
-- carrito. No cambia nada: es solo una cuenta. Un invitado puede (checkout de invitado).

create or replace function public.validate_coupon(
  p_code           text,
  p_subtotal       numeric,
  p_shipping_price numeric default 0,
  p_contact_email  text    default null
)
returns table (
  code            text,
  discount_type   public.coupon_type,
  discount_amount numeric,
  description     text
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_subtotal is null or p_subtotal < 0 then
    raise exception 'El subtotal no es valido.' using errcode = '22023';
  end if;

  return query
    select k.code, k.discount_type, k.discount, k.description
    from public.coupon_check(p_code, p_subtotal, p_shipping_price, p_contact_email, auth.uid(), false) k;
end;
$$;

comment on function public.validate_coupon(text, numeric, numeric, text) is
  'Cuanto descontaria un cupon con ese subtotal y envio. Solo calcula; create_order() lo vuelve a validar al crear el pedido.';

revoke all on function public.validate_coupon(text, numeric, numeric, text) from public;
grant execute on function public.validate_coupon(text, numeric, numeric, text) to anon, authenticated;


-- -----------------------------------------------------------------------------
-- 5. create_order() con cupón
-- -----------------------------------------------------------------------------
-- Misma función de la 0018, con un parámetro nuevo **al final** (`p_coupon_code`, nulo
-- por omisión) y dos columnas más en lo que devuelve (`discount`, `coupon_code`). Se
-- retira la firma anterior (ver la cabecera).

drop function if exists public.create_order(
  text, text, text, text, text, jsonb, text, text, text, text, text, text, boolean
);

drop function if exists public.create_order(
  text, text, text, text, text, jsonb, text, text, text, text, text, text, boolean, text
);

create function public.create_order(
  p_contact_email      text,
  p_full_name          text,
  p_address_line1      text,
  p_shipping_option_id text,
  p_payment_method_id  text,
  p_items              jsonb,
  p_contact_phone      text    default null,
  p_city               text    default null,
  p_postal_code        text    default null,
  p_order_notes        text    default null,
  p_fulfillment_type   text    default 'shipping',
  p_province           text    default null,
  p_wants_installation boolean default false,
  p_coupon_code        text    default null
)
returns table (
  id             uuid,
  order_number   integer,
  subtotal       numeric,
  shipping_price numeric,
  discount       numeric,
  coupon_code    text,
  total          numeric
)
language plpgsql
security definer
set search_path = public
as $$
#variable_conflict use_column
declare
  v_order_id       uuid;
  v_number         integer;
  v_subtotal       numeric(12,2);
  v_shipping_price numeric(12,2);
  v_discount       numeric(12,2) := 0;
  v_coupon_id      bigint;
  v_coupon_code    text;
  v_total          numeric(12,2);
  v_item_count     integer;
  v_fulfillment    public.order_fulfillment;
  v_address        text;
  v_province       text;
  v_wants          boolean;
  v_row            record;
begin
  -- Quién compra. Se pide aquí y no solo en el formulario: es la única puerta.
  if coalesce(btrim(p_contact_email), '') = '' then
    raise exception 'Escribe tu correo electronico.' using errcode = '22023';
  end if;
  if coalesce(btrim(p_full_name), '') = '' then
    raise exception 'Escribe tu nombre completo.' using errcode = '22023';
  end if;
  if coalesce(btrim(p_contact_phone), '') = '' then
    raise exception 'Escribe tu telefono: lo usamos para coordinar la entrega.' using errcode = '22023';
  end if;

  -- Cómo se entrega.
  begin
    v_fulfillment := p_fulfillment_type::public.order_fulfillment;
  exception when invalid_text_representation then
    raise exception 'Tipo de entrega no valido.' using errcode = '22023';
  end;

  -- Un null no es "envio" ni "retiro": sin esto caeria en la rama de retiro.
  if v_fulfillment is null then
    raise exception 'Tipo de entrega no valido.' using errcode = '22023';
  end if;

  if v_fulfillment = 'shipping' then
    v_address  := btrim(coalesce(p_address_line1, ''));
    v_province := btrim(coalesce(p_province, ''));
    if v_address = '' then
      raise exception 'Escribe la direccion de entrega.' using errcode = '22023';
    end if;
    if v_province = '' then
      raise exception 'Elige la provincia de entrega.' using errcode = '22023';
    end if;
  else
    v_address  := 'Retiro en el taller';
    v_province := null;
  end if;

  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Un pedido necesita al menos una pieza.' using errcode = '22023';
  end if;

  if exists (
    select 1 from jsonb_to_recordset(p_items) as i(part_id bigint, quantity integer)
    where i.part_id is null or i.quantity is null or i.quantity <= 0
  ) then
    raise exception 'La cantidad de cada pieza tiene que ser mayor que cero.' using errcode = '22023';
  end if;

  -- El envío sale de la tabla, no del navegador, y tiene que corresponder al tipo
  -- de entrega: retirar en el taller no cuesta envío y enviar no es retirar.
  select s.price into v_shipping_price
  from public.shipping_options s
  where s.id = p_shipping_option_id and s.is_active;

  if v_shipping_price is null then
    raise exception 'Metodo de envio no valido.' using errcode = '22023';
  end if;

  if (v_fulfillment = 'pickup') <> (p_shipping_option_id = 'pickup') then
    raise exception 'La opcion de envio no corresponde al tipo de entrega.' using errcode = '22023';
  end if;

  if not exists (
    select 1 from public.payment_methods m
    where m.id = p_payment_method_id and m.is_active
  ) then
    raise exception 'Metodo de pago no valido.' using errcode = '22023';
  end if;

  -- Se bloquean las piezas, **en orden de id**, antes de mirar el stock: dos
  -- pedidos simultaneos de la ultima unidad no pueden ganar los dos, y dos
  -- pedidos con las mismas piezas en distinto orden no se bloquean entre si.
  perform 1
  from public.hub_parts h
  where h.id in (select i.part_id from jsonb_to_recordset(p_items) as i(part_id bigint))
  order by h.id
  for update;

  -- Subtotal calculado contra el catalogo: solo piezas activas y que quien compra
  -- pueda ver (0013).
  select coalesce(sum(h.price * i.quantity), 0), count(*)
  into v_subtotal, v_item_count
  from jsonb_to_recordset(p_items) as i(part_id bigint, quantity integer)
  join public.hub_parts h
    on h.id = i.part_id
   and h.is_active
   and (not h.is_test or public.can_see_test_items());

  if v_item_count <> jsonb_array_length(p_items) then
    raise exception 'Alguna pieza del carrito ya no esta disponible.' using errcode = '22023';
  end if;

  -- Stock: solo lo de inventario propio. Lo bajo pedido no depende de existencias.
  -- Si el carrito trae la misma pieza dos veces, se suman.
  for v_row in
    select h.id as part_id, h.name, h.stock, sum(i.quantity)::integer as wanted
    from jsonb_to_recordset(p_items) as i(part_id bigint, quantity integer)
    join public.hub_parts h on h.id = i.part_id
    where h.fulfillment = 'stock'
    group by h.id, h.name, h.stock
    order by h.id
  loop
    if v_row.stock <= 0 then
      raise exception 'Se agoto "%". Quitala del carrito para continuar.', v_row.name
        using errcode = '22023';
    elsif v_row.wanted > v_row.stock then
      raise exception 'De "%" solo quedan % y pediste %. Ajusta la cantidad.',
        v_row.name, v_row.stock, v_row.wanted
        using errcode = '22023';
    end if;
  end loop;

  -- La instalacion solo se puede pedir si algo del pedido se instala.
  v_wants := coalesce(p_wants_installation, false) and exists (
    select 1
    from jsonb_to_recordset(p_items) as i(part_id bigint, quantity integer)
    join public.hub_parts h on h.id = i.part_id
    where h.installable
  );

  -- El cupón, con la fila bloqueada: dos pedidos a la vez no se llevan el último uso.
  -- Un código vacío es "sin cupón".
  if coalesce(btrim(p_coupon_code), '') <> '' then
    select k.coupon_id, k.code, k.discount
      into v_coupon_id, v_coupon_code, v_discount
    from public.coupon_check(p_coupon_code, v_subtotal, v_shipping_price, p_contact_email, auth.uid(), true) k;
  end if;

  v_total := v_subtotal + v_shipping_price - v_discount;

  insert into public.orders (
    user_id, contact_email, contact_phone, full_name, address_line1,
    city, postal_code, province, shipping_option_id, payment_method_id, order_notes,
    fulfillment_type, wants_installation,
    subtotal, shipping_price, discount, coupon_id, coupon_code, total, status
  ) values (
    auth.uid(), btrim(p_contact_email), btrim(p_contact_phone), btrim(p_full_name), v_address,
    nullif(btrim(coalesce(p_city, '')), ''), nullif(btrim(coalesce(p_postal_code, '')), ''),
    v_province, p_shipping_option_id, p_payment_method_id, nullif(btrim(coalesce(p_order_notes, '')), ''),
    v_fulfillment, v_wants,
    v_subtotal, v_shipping_price, v_discount, v_coupon_id, v_coupon_code, v_total, 'awaiting_payment'
  )
  returning orders.id, orders.order_number into v_order_id, v_number;

  -- El nombre y el precio se congelan aqui, como ya documentaba el esquema. Y lo
  -- que se descuenta queda anotado en la linea, para poder devolverlo.
  insert into public.order_items (order_id, part_id, name, unit_price, quantity, stock_deducted)
  select v_order_id, h.id, h.name, h.price, i.quantity,
         case when h.fulfillment = 'stock' then i.quantity else 0 end
  from jsonb_to_recordset(p_items) as i(part_id bigint, quantity integer)
  join public.hub_parts h on h.id = i.part_id;

  update public.hub_parts h
     set stock = h.stock - d.qty
    from (select oi.part_id, sum(oi.stock_deducted) as qty
            from public.order_items oi
           where oi.order_id = v_order_id and oi.stock_deducted > 0
           group by oi.part_id) d
   where h.id = d.part_id;

  return query select v_order_id, v_number, v_subtotal, v_shipping_price, v_discount, v_coupon_code, v_total;
end;
$$;

comment on function public.create_order(
  text, text, text, text, text, jsonb, text, text, text, text, text, text, boolean, text
) is 'Crea un pedido: precios, envio y descuento de la base, stock validado y descontado, estado awaiting_payment.';

-- Se le da a `anon` a propósito: el checkout de invitado existe (0002) y esta es la
-- única puerta por la que el navegador puede crear un pedido.
revoke all on function public.create_order(
  text, text, text, text, text, jsonb, text, text, text, text, text, text, boolean, text
) from public;

grant execute on function public.create_order(
  text, text, text, text, text, jsonb, text, text, text, text, text, text, boolean, text
) to anon, authenticated;


-- -----------------------------------------------------------------------------
-- 6. get_order() dice el descuento
-- -----------------------------------------------------------------------------

create or replace function public.get_order(p_order_id uuid)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'id',                    o.id,
    'order_number',          o.order_number,
    'status',                o.status,
    'fulfillment_type',      o.fulfillment_type,
    'payment_method_id',     o.payment_method_id,
    'wants_installation',    o.wants_installation,
    'subtotal',              o.subtotal,
    'shipping_price',        o.shipping_price,
    'discount',              o.discount,
    'coupon_code',           o.coupon_code,
    'total',                 o.total,
    'created_at',            o.created_at,
    'has_proof',             o.payment_proof_url is not null,
    'whatsapp_opened_at',    o.whatsapp_opened_at,
    'payment_confirmed_at',  o.payment_confirmed_at,
    'installation_service_id', (
      select h.installation_service_id
      from public.order_items oi
      join public.hub_parts h on h.id = oi.part_id
      where oi.order_id = o.id and h.installable and h.installation_service_id is not null
      order by oi.id
      limit 1
    ),
    'items', coalesce((
      select jsonb_agg(jsonb_build_object(
               'name', oi.name, 'unit_price', oi.unit_price, 'quantity', oi.quantity
             ) order by oi.id)
      from public.order_items oi where oi.order_id = o.id
    ), '[]'::jsonb),
    'history', coalesce((
      select jsonb_agg(jsonb_build_object(
               'from_status', hs.from_status, 'to_status', hs.to_status,
               'note', hs.note, 'created_at', hs.created_at
             ) order by hs.created_at, hs.id)
      from public.order_status_history hs where hs.order_id = o.id
    ), '[]'::jsonb)
  )
  from public.orders o
  where o.id = p_order_id;
$$;

revoke all on function public.get_order(uuid) from public;
grant execute on function public.get_order(uuid) to anon, authenticated;


-- -----------------------------------------------------------------------------
-- 7. admin_coupon_usage(): cuántas veces se usó cada cupón
-- -----------------------------------------------------------------------------
-- `security invoker`: RLS de `orders` decide qué ve quien llama, así que a un admin le
-- devuelve el total y a un cliente solo lo suyo. Los cancelados no cuentan (devuelven
-- el uso, igual que en `coupon_check()`).

create or replace function public.admin_coupon_usage()
returns table (coupon_id bigint, uses bigint)
language sql
stable
security invoker
set search_path = public
as $$
  select o.coupon_id, count(*)
  from public.orders o
  where o.coupon_id is not null and o.status <> 'cancelled'
  group by o.coupon_id;
$$;

revoke all on function public.admin_coupon_usage() from public;
revoke execute on function public.admin_coupon_usage() from anon;
grant execute on function public.admin_coupon_usage() to authenticated;
