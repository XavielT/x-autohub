-- =============================================================================
-- X AutoHub — Avisos push para quien compró sin cuenta
-- =============================================================================
--
-- Hasta aquí solo recibía avisos quien tenía cuenta (`push_subscriptions` es por usuario), y un pedido de
-- invitado se quedaba sin nadie a quien avisar. Esta migración deja que un invitado active los avisos de
-- **su pedido** desde `/pedido/:id`.
--
--   · `order_push_subscriptions`: un dispositivo atado a **un pedido**, no a una cuenta. Sin RLS abierta y
--     sin permisos para el navegador: la lee y la borra `send-push` con la clave de servicio.
--   · `register_order_push()` / `unregister_order_push()`: la única forma de guardar y quitar uno.
--   · `notify_status_change()` ya no ignora los pedidos sin dueño: si el pedido tiene dispositivos, avisa.
--
--
-- LO QUE SE DECIDIÓ
-- ------------------
-- · **El uuid del pedido es la llave**, como ya lo es para ver `/pedido/:id` (`get_order()` es público por
--   id). Quien conoce el id puede pedir avisos de ese pedido, que es exactamente lo que ya puede leer.
--   Un uuid no se adivina; por eso no hace falta pedir nada más al invitado (ni correo ni teléfono).
-- · **Los tres rechazos usan el código 22023** (parámetro no válido): es el único que la interfaz deja pasar con su mensaje
--   en español (ver `translateDbError`), y aquí el mensaje es justo lo que el invitado necesita leer.
-- · **Solo pedidos de invitado.** Si el pedido tiene dueño, los avisos van a su cuenta y registrar un
--   dispositivo aquí daría avisos duplicados: la función lo rechaza.
-- · **Solo pedidos en marcha.** Uno entregado o cancelado ya no cambia de estado; no tiene sentido suscribirse.
-- · **Hasta 3 dispositivos por pedido** (el invitado, su pareja, su teléfono y su tableta). Registrar el mismo
--   dispositivo otra vez no cuenta dos veces.
-- · **La unicidad es por pedido y dispositivo**, no global como en las cuentas: la misma persona con dos pedidos
--   tiene dos filas con el mismo `endpoint`, una por pedido.
-- · **Se limpia solo.** Las filas se borran con el pedido (`on delete cascade`) y `send-push` las borra al
--   mandar el aviso de un estado final (entregado o cancelado).
-- · **Las citas de invitado quedan fuera.** Esta migración es solo de pedidos.
-- · **Sin los secretos del Vault no se avisa, y tampoco falla**, como en la 0028.
--
--
-- ORDEN DE DESPLIEGUE
-- -------------------
-- Función `send-push` nueva (lee los dispositivos del pedido) → migración → frontend. Con la migración y la función
-- vieja, el trigger llamaría a `send-push` y esta respondería `guest`: no pasa nada. El frontend anterior no sabe de
-- esto y sigue funcionando.
--
-- ESTA MIGRACIÓN SE PUEDE EJECUTAR DOS VECES: `if not exists`, `create or replace` y `drop ... if exists`.
-- =============================================================================

create table if not exists public.order_push_subscriptions (
  id         bigint generated by default as identity primary key,
  order_id   uuid    not null references public.orders(id) on delete cascade,
  endpoint   text    not null check (endpoint like 'https://%' and char_length(endpoint) <= 2048),
  p256dh     text    not null check (char_length(p256dh) between 80 and 100),
  auth       text    not null check (char_length(auth) between 20 and 30),
  user_agent text    not null default '' check (char_length(user_agent) <= 300),
  created_at timestamptz not null default now(),
  unique (order_id, endpoint)
);

create index if not exists order_push_subscriptions_order_idx on public.order_push_subscriptions (order_id);

comment on table public.order_push_subscriptions is
  'Dispositivos de quien compró sin cuenta, atados a un pedido (0034). Se escribe con register_order_push(); la lee y la borra send-push.';

-- Nadie del navegador la toca: sin políticas y sin permisos. `send-push` entra con `service_role`.
alter table public.order_push_subscriptions enable row level security;
revoke all on public.order_push_subscriptions from public;
revoke all on public.order_push_subscriptions from anon;
revoke all on public.order_push_subscriptions from authenticated;
grant select, insert, update, delete on public.order_push_subscriptions to service_role;


-- -----------------------------------------------------------------------------
-- register_order_push(): activar los avisos de un pedido de invitado
-- -----------------------------------------------------------------------------
create or replace function public.register_order_push(
  p_order_id   uuid,
  p_endpoint   text,
  p_p256dh     text,
  p_auth       text,
  p_user_agent text default ''
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  c_max_devices constant integer := 3;
  v_owner  uuid;
  v_status public.order_status;
begin
  select o.user_id, o.status into v_owner, v_status from public.orders o where o.id = p_order_id;

  if not found then
    raise exception 'Ese pedido no existe.' using errcode = '22023';
  end if;

  if v_owner is not null then
    raise exception 'Este pedido es de una cuenta: inicia sesion y activa los avisos desde tu perfil.' using errcode = '22023';
  end if;

  if v_status in ('delivered', 'cancelled') then
    raise exception 'Este pedido ya termino: no va a cambiar de estado.' using errcode = '22023';
  end if;

  -- El mismo dispositivo otra vez es una actualizacion, no un dispositivo mas.
  if not exists (
       select 1 from public.order_push_subscriptions s where s.order_id = p_order_id and s.endpoint = p_endpoint
     )
     and (select count(*) from public.order_push_subscriptions s where s.order_id = p_order_id) >= c_max_devices then
    raise exception 'Este pedido ya avisa a % dispositivos.', c_max_devices using errcode = '22023';
  end if;

  insert into public.order_push_subscriptions (order_id, endpoint, p256dh, auth, user_agent)
  values (p_order_id, p_endpoint, p_p256dh, p_auth, left(coalesce(p_user_agent, ''), 300))
  on conflict (order_id, endpoint) do update
    set p256dh = excluded.p256dh, auth = excluded.auth, user_agent = excluded.user_agent;
end;
$$;

comment on function public.register_order_push(uuid, text, text, text, text) is
  'Un invitado activa los avisos de su pedido en este dispositivo (0034). El uuid del pedido es la llave, como en get_order().';

revoke all on function public.register_order_push(uuid, text, text, text, text) from public;
grant execute on function public.register_order_push(uuid, text, text, text, text) to anon, authenticated;


-- -----------------------------------------------------------------------------
-- unregister_order_push(): quitar este dispositivo de un pedido
-- -----------------------------------------------------------------------------
create or replace function public.unregister_order_push(p_order_id uuid, p_endpoint text)
returns void
language sql
security definer
set search_path = public
as $$
  delete from public.order_push_subscriptions where order_id = p_order_id and endpoint = p_endpoint;
$$;

revoke all on function public.unregister_order_push(uuid, text) from public;
grant execute on function public.unregister_order_push(uuid, text) to anon, authenticated;


-- -----------------------------------------------------------------------------
-- notify_status_change(): ya no ignora los pedidos sin dueño
-- -----------------------------------------------------------------------------
-- La de la 0028, con un cambio: un pedido sin dueño avisa si tiene dispositivos suscritos. Una cita sin dueño sigue
-- sin avisar. Sin dispositivos no se hace ninguna llamada (no tiene sentido despertar a `send-push` por nada).
create or replace function public.notify_status_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_url    text;
  v_anon   text;
  v_secret text;
begin
  if new.user_id is null then
    -- Sin dueño: solo un pedido con dispositivos de invitado.
    if tg_table_name <> 'orders'
       or not exists (select 1 from public.order_push_subscriptions s where s.order_id = new.id) then
      return null;
    end if;
  elsif new.user_id = auth.uid() then
    -- Quien cambia lo suyo ya lo sabe.
    return null;
  end if;

  begin
    select max(decrypted_secret) filter (where name = 'send_push_url'),
           max(decrypted_secret) filter (where name = 'send_push_anon_key'),
           max(decrypted_secret) filter (where name = 'send_push_secret')
      into v_url, v_anon, v_secret
      from vault.decrypted_secrets
     where name in ('send_push_url', 'send_push_anon_key', 'send_push_secret');

    if coalesce(v_url, '') = '' or coalesce(v_anon, '') = '' or coalesce(v_secret, '') = '' then
      return null;
    end if;

    perform net.http_post(
      url     := v_url,
      body    := jsonb_build_object(
                   'kind', case tg_table_name when 'orders' then 'order' else 'appointment' end,
                   'id',   new.id
                 ),
      headers := jsonb_build_object(
                   'Content-Type',  'application/json',
                   'Authorization', 'Bearer ' || v_anon,
                   'x-push-secret', v_secret
                 )
    );
  exception when others then
    raise warning 'notify_status_change: %', sqlerrm;
  end;

  return null;
end;
$$;

comment on function public.notify_status_change() is
  'Trigger: cuando cambia el estado de un pedido o de una cita con dueño (o de un pedido de invitado con dispositivos), le pide a la Edge Function send-push que avise (pg_net, con los secretos del Vault). Nunca hace fallar el cambio.';

-- Una función de trigger no se invoca por rpc, pero se cierra igual (las tres líneas).
revoke all on function public.notify_status_change() from public;
revoke execute on function public.notify_status_change() from anon;
revoke execute on function public.notify_status_change() from authenticated;
