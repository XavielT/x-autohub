-- -----------------------------------------------------------------------------
-- Perfiles — extiende auth.users con los datos que la app muestra
-- -----------------------------------------------------------------------------
create table if not exists public.profiles (
  id            uuid primary key references auth.users(id) on delete cascade,
  display_name  text        not null,
  email         text        not null,
  phone         text,
  location      text,
  avatar_url    text,
  -- Cuenta verificada por el equipo de X AutoHub (insignia en publicaciones).
  is_verified   boolean     not null default false,
  -- Permite publicar en el inventario propio (Auto Hub, Catálogo, noticias).
  is_admin      boolean     not null default false,
  created_at    timestamptz not null default now()
);

comment on table public.profiles is
  'Datos públicos del usuario. Se crea automáticamente al registrarse (trigger on_auth_user_created).';

-- Crea el perfil en cuanto Supabase Auth registra al usuario, tomando el
-- display_name de los metadatos que manda el formulario de registro.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name, email, phone, location)
  values (
    new.id,
    coalesce(
      nullif(new.raw_user_meta_data ->> 'display_name', ''),
      split_part(new.email, '@', 1)
    ),
    new.email,
    nullif(new.raw_user_meta_data ->> 'phone', ''),
    nullif(new.raw_user_meta_data ->> 'location', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- -----------------------------------------------------------------------------
-- AUTO HUB — inventario propio de X AutoHub, verificado por el equipo
-- -----------------------------------------------------------------------------
create type public.chasis_type as enum ('sedan', 'suv', 'hatchback', 'pickup');
create type public.traction_type as enum ('fwd', 'rwd', 'awd', '4x4');
create type public.fuel_type as enum ('gasoline', 'diesel', 'glp', 'electric');

create table if not exists public.auto_hub_vehicles (
  id           bigint generated by default as identity primary key,
  brand        text          not null,
  model        text          not null,
  year         smallint      not null check (year between 1900 and 2100),
  price        numeric(12,2) not null check (price >= 0),
  color        text          not null,
  mileage      integer       not null check (mileage >= 0),
  chasis_type  public.chasis_type   not null,
  doors        smallint      not null check (doors between 1 and 8),
  traction     public.traction_type not null,
  fuel         public.fuel_type     not null,
  cylinders    smallint      not null check (cylinders between 0 and 16),
  images       text[]        not null default '{}',
  description  text          not null default '',
  location     text          not null,
  -- Teléfono de contacto. text, no numérico: un 809... con formato no es un número.
  contact      text          not null,
  is_available boolean       not null default true,
  created_at   timestamptz   not null default now()
);

create index if not exists auto_hub_vehicles_available_idx
  on public.auto_hub_vehicles (is_available, created_at desc);
create index if not exists auto_hub_vehicles_brand_model_idx
  on public.auto_hub_vehicles (brand, model);

-- -----------------------------------------------------------------------------
-- CATÁLOGO — tienda propia de piezas (la que tiene carrito y checkout)
