create type public.order_status as enum ('pending', 'paid', 'shipped', 'delivered', 'cancelled');

create table if not exists public.orders (
  id                 uuid primary key default gen_random_uuid(),
  -- Nulo permitido: se puede comprar sin cuenta (checkout de invitado).
  user_id            uuid references public.profiles(id) on delete set null,
  contact_email      text          not null,
  contact_phone      text,
  full_name          text          not null,
  address_line1      text          not null,
  city               text,
  postal_code        text,
  shipping_option_id text          not null references public.shipping_options(id),
  payment_method_id  text          not null references public.payment_methods(id),
  order_notes        text,
  subtotal           numeric(12,2) not null check (subtotal >= 0),
  shipping_price     numeric(12,2) not null default 0 check (shipping_price >= 0),
  total              numeric(12,2) not null check (total >= 0),
  status             public.order_status not null default 'pending',
  created_at         timestamptz   not null default now()
);

create index if not exists orders_user_idx on public.orders (user_id, created_at desc);

create table if not exists public.order_items (
  id         bigint generated by default as identity primary key,
  order_id   uuid   not null references public.orders(id) on delete cascade,
  part_id    bigint references public.hub_parts(id) on delete set null,
  -- Copia del nombre y precio al momento de comprar: si la pieza cambia de
  -- precio después, el pedido histórico no se altera.
  name       text          not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity   integer       not null check (quantity > 0)
);

create index if not exists order_items_order_idx on public.order_items (order_id);
