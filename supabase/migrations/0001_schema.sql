create table if not exists public.hub_parts (
  id                  bigint generated by default as identity primary key,
  category            text          not null,
  name                text          not null,
  brand               text          not null,
  img_url             text          not null,
  images              text[]        not null default '{}',
  stars_calification  numeric(2,1)  not null default 0 check (stars_calification between 0 and 5),
  price               numeric(12,2) not null check (price >= 0),
  description         text          not null default '',
  stock               integer       not null default 0 check (stock >= 0),
  is_active           boolean       not null default true,
  created_at          timestamptz   not null default now()
);

create index if not exists hub_parts_category_idx on public.hub_parts (category) where is_active;
-- Búsqueda por nombre/marca sin distinguir acentos ni mayúsculas.
create index if not exists hub_parts_search_idx
  on public.hub_parts using gin (to_tsvector('spanish', name || ' ' || brand));

-- -----------------------------------------------------------------------------
-- HUB MARKET — clasificados publicados por la comunidad
-- -----------------------------------------------------------------------------
create type public.hub_market_category as enum ('vehiculos', 'piezas', 'accesorios');
create type public.item_condition as enum ('new', 'used');

create table if not exists public.hub_market_items (
  id           bigint generated by default as identity primary key,
  seller_id    uuid references public.profiles(id) on delete set null,
  -- Nombre del vendedor para el contenido sembrado (sin usuario real detrás).
  -- Cuando seller_id existe, el nombre sale del perfil; esto es el fallback.
  seller_name  text          not null,
  title        text          not null,
  description  text          not null default '',
  images       text[]        not null default '{}',
  price        numeric(12,2) not null check (price >= 0),
  location     text          not null,
  category     public.hub_market_category not null,
  condition    public.item_condition,
  is_featured  boolean       not null default false,
  is_active    boolean       not null default true,
  -- Especificaciones de vehículo, planas en vez de jsonb para poder filtrar
  -- por rango (año, kilometraje) con índices.
  spec_year        smallint,
  spec_mileage     integer,
  spec_hp          integer,
  spec_zero_to_100 numeric(4,1),
  spec_top_speed   integer,
  spec_brand       text,
  spec_model       text,
  created_at   timestamptz   not null default now(),
  -- Un vehículo sin año no sirve de nada en un clasificado.
  constraint hub_market_vehicle_needs_year
    check (category <> 'vehiculos' or spec_year is not null)
);

create index if not exists hub_market_items_category_idx
  on public.hub_market_items (category, created_at desc) where is_active;
create index if not exists hub_market_items_seller_idx
  on public.hub_market_items (seller_id);
create index if not exists hub_market_items_featured_idx
  on public.hub_market_items (is_featured, created_at desc) where is_active;

