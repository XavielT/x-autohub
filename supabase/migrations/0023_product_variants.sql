-- =============================================================================
-- X AutoHub — Variantes de producto: color, talla… (después del pivote)
-- =============================================================================
--
-- Hasta aquí un accesorio en tres colores eran tres productos, cada uno con su ficha,
-- su stock y sus reseñas. Esta migración deja un producto con **opciones**: "Alfombras
-- all-weather" con "Negro", "Gris" y "Beige", cada una con su propio stock.
--
--   1. `product_variants`: las opciones de un producto (un nombre y su stock).
--   2. `hub_parts.variant_label` ("Color", "Talla"…) y `hub_parts.has_variants`.
--   3. Un trigger mantiene `hub_parts.stock` como **la suma del stock de las opciones
--      activas**, y `has_variants`. Así la tarjeta, el filtro "solo en stock" y
--      `search_products()` siguen diciendo la verdad sin tocar su lógica.
--   4. `order_items.variant_id`: qué opción se compró.
--   5. `create_order()` y `set_order_status()` descuentan y devuelven el stock **de la
--      opción** cuando la línea trae una.
--   6. `search_products()` devuelve `has_variants` y `variant_label` (la tarjeta necesita
--      saber si hay que elegir antes de agregar).
--
--
-- LO QUE SE DECIDIÓ
-- ------------------
-- · **Una sola dimensión.** Una opción es un nombre ("Rojo", "Talla M", "Rojo / M"). Una
--   combinación de dos dimensiones se escribe en el nombre. Una matriz real (color ×
--   talla con su propio stock cada celda) es otro proyecto, y casi todo accesorio es una
--   cosa o la otra.
--
-- · **Las opciones comparten el precio del producto.** Nada de precio por opción: la
--   tarjeta, el JSON-LD y los cupones hablan de un solo precio por producto, y mostrar
--   "RD$ 1,000" en la tarjeta para algo que en talla L cuesta 1,200 sería mentir. Si una
--   talla cuesta distinto, es otro producto.
--
-- · **Un producto con opciones activas exige elegir una al comprar**, y uno sin opciones
--   no acepta ninguna. `create_order()` lo comprueba por dentro: el navegador no manda
--   un precio, pero sí una opción, y se valida igual.
--
-- · **El nombre de la línea del pedido es "Producto · Opción"** y se congela como el resto
--   (`order_items.name`), así que el pedido, el panel y el WhatsApp lo muestran sin
--   cambiar nada.
--
-- · **Una opción que ya tuvo pedidos no se puede borrar** (`on delete restrict`): borrarla
--   dejaría una línea que no sabe a qué stock devolver si se cancela. Se apaga
--   (`is_active = false`). Por lo mismo, un producto con pedidos de opciones tampoco se
--   puede borrar; se apaga.
--
-- · **`hub_parts.stock` de un producto con opciones es derivado.** Se recalcula cada vez
--   que cambia una opción; el panel lo muestra de solo lectura. Un producto bajo pedido
--   con opciones sigue sin depender del stock.
--
--
-- ORDEN DE DESPLIEGUE
-- -------------------
-- **Primero esta migración, después el frontend.** `create_order()` conserva su firma (las
-- opciones viajan dentro de `p_items`), así que el frontend anterior sigue funcionando:
-- ningún producto tiene opciones hasta que el equipo cree la primera. `search_products()`
-- gana dos columnas de salida; el frontend anterior las ignora.
--
--
-- ESTA MIGRACIÓN SE PUEDE EJECUTAR DOS VECES
-- ------------------------------------------
-- Todo lleva `if not exists` / `create or replace` / `drop ... if exists`.
-- =============================================================================


