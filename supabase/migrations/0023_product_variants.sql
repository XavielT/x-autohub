-- -----------------------------------------------------------------------------
-- 2. La tabla de opciones
-- -----------------------------------------------------------------------------

create table if not exists public.product_variants (
  id         bigint generated by default as identity primary key,
  product_id bigint  not null references public.hub_parts(id) on delete cascade,
  -- "Negro", "Talla M", "Rojo / M": sin espacios a los lados, de 1 a 40 caracteres.
  name       text    not null
               check (name = btrim(name) and char_length(name) between 1 and 40),
  -- Opcional. Único cuando existe.
  sku        text,
  stock      integer not null default 0 check (stock >= 0),
  sort_order integer not null default 0,
  is_active  boolean not null default true,
  created_at timestamptz not null default now()
);

-- El mismo nombre dos veces en un producto confundiría a quien elige.
create unique index if not exists product_variants_name_key
  on public.product_variants (product_id, lower(name));
create unique index if not exists product_variants_sku_key
  on public.product_variants (sku) where sku is not null;
create index if not exists product_variants_product_idx
  on public.product_variants (product_id, sort_order, id);

comment on table public.product_variants is
  'Opciones de un producto (color, talla…), cada una con su stock. Comparten el precio del producto.';

alter table public.product_variants enable row level security;

-- Las ve quien puede ver el producto (el `exists` sobre hub_parts aplica su RLS: un
-- producto de prueba o apagado no enseña sus opciones). Un admin ve también las apagadas.
drop policy if exists "las opciones las ve quien ve el producto" on public.product_variants;
create policy "las opciones las ve quien ve el producto"
  on public.product_variants for select
  using (
    (is_active or public.is_admin())
    and exists (select 1 from public.hub_parts p where p.id = product_variants.product_id)
  );

drop policy if exists "solo admin gestiona las opciones" on public.product_variants;
create policy "solo admin gestiona las opciones"
  on public.product_variants for all
  using (public.is_admin())
  with check (public.is_admin());

-- Defensa en profundidad: los default privileges de Supabase le dan a `anon` permiso de
-- escritura sobre las tablas nuevas y solo RLS lo detiene.
revoke insert, update, delete on public.product_variants from anon;


-- -----------------------------------------------------------------------------
-- 3. El stock del producto es la suma de sus opciones activas
-- -----------------------------------------------------------------------------

create or replace function public.product_variants_sync()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_product bigint;
begin
  -- El producto de la fila vieja y el de la nueva (si cambió de producto, los dos).
  for v_product in
    select distinct x
    from unnest(array[
      case when tg_op <> 'INSERT' then old.product_id end,
      case when tg_op <> 'DELETE' then new.product_id end
    ]) as x
    where x is not null
  loop
    update public.hub_parts p
       set has_variants = exists (
             select 1 from public.product_variants v where v.product_id = p.id and v.is_active
           ),
           -- Con opciones activas el stock es la suma; si ya no queda ninguna, se deja
           -- como estaba para que el panel lo pueda volver a editar a mano.
           stock = case
             when exists (select 1 from public.product_variants v where v.product_id = p.id and v.is_active)
               then (select coalesce(sum(v.stock), 0) from public.product_variants v
                      where v.product_id = p.id and v.is_active)
             else p.stock
           end
     where p.id = v_product;
  end loop;

  return null;
end;
$$;

drop trigger if exists product_variants_sync on public.product_variants;
create trigger product_variants_sync
  after insert or update or delete on public.product_variants
  for each row execute function public.product_variants_sync();

-- Función de trigger: no se llama a mano. Las tres líneas de siempre (`revoke ... from
-- public` no le quita nada a `anon`: los default privileges le dan un grant directo).
revoke all on function public.product_variants_sync() from public, anon, authenticated;


